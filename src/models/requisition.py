"""Requisition and Farvision ERP catalog domain models."""

from datetime import date
from decimal import Decimal
from enum import Enum
from pydantic import BaseModel, Field


class UnitOfMeasure(str, Enum):
    """Supported construction units of measure."""
    SQFT = "sq.ft"
    SQM = "sq.m"
    DRUM = "drum"
    LITRE = "litre"
    KG = "kg"
    MT = "mt"
    NOS = "nos"


class FarvisionCatalogItem(BaseModel):
    """Canonical item from Farvision ERP catalog."""
    item_code: str = Field(..., description="Unique Farvision item code e.g. 'MAT-WP-0042'")
    canonical_name: str = Field(..., description="Standardized material name")
    category: str = Field(..., description="Trade category e.g. 'Waterproofing'")
    standard_unit: UnitOfMeasure = Field(..., description="Canonical unit in BOQ")
    budget_rate: Decimal = Field(..., ge=0, description="Approved baseline rate per unit in INR")


class SiteRequisition(BaseModel):
    """Site material requirement generated by site engineer."""
    requisition_id: str = Field(..., description="Unique requisition identifier")
    project_name: str = Field(..., description="Project e.g. 'Vinayak Amara'")
    tower: str = Field(..., description="Tower or location e.g. 'Tower-2'")
    item_code: str = Field(..., description="Matched Farvision item code")
    material_description: str = Field(..., description="Specific specification details")
    requested_quantity: Decimal = Field(..., gt=0, description="Quantity requested")
    target_unit: UnitOfMeasure = Field(..., description="Requested unit")
    required_by_date: date = Field(..., description="Date material is required at site")
